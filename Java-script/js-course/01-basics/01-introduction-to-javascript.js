/* ============================================================
   TOPIC: Introduction to JavaScript
   ============================================================
   JavaScript (JS) is a programming language that runs inside
   the browser (and also on servers via Node.js). It's what
   makes websites interactive - reacting to clicks, updating
   content, validating forms, etc.

   HTML   -> structure (the skeleton of the page)
   CSS    -> style (how it looks)
   JS     -> behaviour (how it acts/reacts)
============================================================ */

// console.log() prints a message to the console.
// It's the most common way to check what your code is doing.
console.log("Hello, World!");

// You can print numbers, strings, or the result of calculations.
console.log(10 + 5);          // prints 15
console.log("JS is fun!");    // prints the string as-is

// Comments (like this one) are ignored by JavaScript.
// Use // for single-line comments...
/* ...and /* */ /* for multi-line comments (like the block above). */

// Semicolons end a statement. JS can often work without them,
// but using them consistently avoids subtle bugs.
console.log("Statement 1");
